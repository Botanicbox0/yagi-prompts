/**
 * Writes lib/brand-studio/prompt-shield/glyph-widths.ts from the bundled server font
 * (assets/fonts/server/Pretendard-Regular.otf): the advance of every character the prompt pages may draw.
 * Run after replacing the font: `npx tsx scripts/prompt-shield-glyph-table.ts`.
 * tests/brand-studio/prompt-shield/layout.test.ts fails while the table and the font disagree.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { drawableRuns, SERVER_FONT_FILE } from '../lib/brand-studio/prompt-shield/glyph-source';
import { readFontMetrics } from '../lib/brand-studio/prompt-shield/font-metrics';

const root = process.cwd();
const metrics = readFontMetrics(new Uint8Array(readFileSync(path.join(root, SERVER_FONT_FILE))));
const runs = drawableRuns(metrics);
const body = runs.map(([start, end, advance]) => `${start.toString(36)},${end.toString(36)},${advance.toString(36)}`).join(';');
const out = `/**
 * GENERATED by scripts/prompt-shield-glyph-table.ts from ${SERVER_FONT_FILE}. Do not edit by hand.
 * Runs of characters the prompt pages may draw: "start,end,advance" in base 36, separated by ";".
 * Every character outside these runs is drawn as the replacement box (./layout.ts).
 */
export const GLYPH_UNITS_PER_EM = ${metrics.unitsPerEm};
export const GLYPH_RUNS = '${body}';
`;
writeFileSync(path.join(root, 'lib/brand-studio/prompt-shield/glyph-widths.ts'), out);
console.log(`runs: ${runs.length}, bytes: ${out.length}`);
