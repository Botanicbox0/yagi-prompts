/**
 * Brand Studio v5 — Org Workflows & Knowledge Hub wire contracts (`docs/STUDIO-PRO-SUITE-V4.md` §1.5).
 *
 * Client-safe: zod schemas and TypeScript types only (no env, no db, no node:* imports).
 */
import { z } from 'zod';
import {
  STUDIO_ASSET_ROLES,
  STUDIO_AUDIO_MODES,
  type StudioAllowanceView,
  type StudioAssetRole,
  type StudioAudioMode,
  type StudioFailure,
  type StudioJobKind,
  type StudioJobView,
} from '@/lib/brand-studio/contracts';

export const WORKFLOW_CATEGORIES = ['character', 'product', 'video', 'campaign', 'custom'] as const;
export type WorkflowCategory = (typeof WORKFLOW_CATEGORIES)[number];

export const WORKFLOW_SOURCES = ['starter', 'saved_run', 'ai_builder', 'mcp', 'web'] as const;
export type WorkflowSource = (typeof WORKFLOW_SOURCES)[number];

export const PLAYBOOK_STATUSES = ['draft', 'published'] as const;
export type PlaybookStatus = (typeof PLAYBOOK_STATUSES)[number];

export const WORKFLOW_OPERATIONS = [
  'create',
  'update',
  'delete',
  'run',
  'save_from_job',
  'build_with_ai',
  'save_playbook',
  'delete_playbook',
] as const;
export type WorkflowOperation = (typeof WORKFLOW_OPERATIONS)[number];

export function isWorkflowOperation(value: unknown): value is WorkflowOperation {
  return typeof value === 'string' && (WORKFLOW_OPERATIONS as readonly string[]).includes(value);
}

/* ----------------------------------------------------------- recipe schema */

export const WORKFLOW_SLOT_KINDS = ['image_ref', 'video_ref', 'text', 'textarea', 'multiselect', 'folder'] as const;
export type WorkflowSlotKind = (typeof WORKFLOW_SLOT_KINDS)[number];

export const WorkflowSlotOptionSchema = z.object({
  id: z.string().trim().min(1).max(40),
  label: z.string().trim().min(1).max(80),
  labelEn: z.string().trim().min(1).max(80).optional(),
  defaultSelected: z.boolean().optional(),
});
export type WorkflowSlotOption = z.infer<typeof WorkflowSlotOptionSchema>;

export const WorkflowInputSlotSchema = z.object({
  key: z.string().trim().min(1).max(40),
  kind: z.enum(WORKFLOW_SLOT_KINDS),
  label: z.string().trim().min(1).max(80),
  labelEn: z.string().trim().min(1).max(80).optional(),
  placeholder: z.string().trim().max(160).optional(),
  placeholderEn: z.string().trim().max(160).optional(),
  required: z.boolean().default(false),
  role: z.enum(STUDIO_ASSET_ROLES).optional(),
  options: z.array(WorkflowSlotOptionSchema).max(8).optional(),
  defaultValue: z.string().trim().max(120).optional(),
});
export type WorkflowInputSlot = z.infer<typeof WorkflowInputSlotSchema>;

export const WorkflowStepSchema = z.object({
  id: z.string().trim().min(1).max(40),
  label: z.string().trim().min(1).max(100),
  labelEn: z.string().trim().min(1).max(100).optional(),
  /** Optional pack option id (e.g. `turnaround`, `expressions`, `details`) that toggles this step. */
  packId: z.string().trim().min(1).max(40).optional(),
  /** Runs first only when the user did not attach `@image1`, establishing a hero front reference. */
  onlyWhenNoImageRef: z.boolean().optional(),
  /** Uses the hero reference generated by an earlier `onlyWhenNoImageRef` step when `@image1` was omitted. */
  useHeroOutputAsRef: z.boolean().optional(),
  medium: z.enum(['image', 'video']),
  model: z.string().trim().min(1).max(60),
  aspect: z.string().trim().min(3).max(8),
  resolution: z.string().trim().min(2).max(8),
  seconds: z.number().int().min(4).max(15).optional(),
  audio: z.enum(STUDIO_AUDIO_MODES).optional(),
  count: z.number().int().min(1).max(4).default(1),
  promptTemplate: z.string().trim().min(1).max(3200),
  useReferenceSlots: z.array(z.string().trim().min(1).max(40)).max(6).default([]),
});
export type WorkflowStep = z.infer<typeof WorkflowStepSchema>;

export const WorkflowRecipeSchema = z.object({
  version: z.literal(1).default(1),
  guide: z.string().trim().max(1200).default(''),
  guideEn: z.string().trim().max(1200).optional(),
  defaultFolderPattern: z.string().trim().max(60).optional(),
  defaultFolderPatternEn: z.string().trim().max(60).optional(),
  consistencyCheck: z.enum(['character_sheet', 'none']).default('none'),
  slots: z.array(WorkflowInputSlotSchema).max(10).default([]),
  steps: z.array(WorkflowStepSchema).min(1).max(6),
});
export type WorkflowRecipe = z.infer<typeof WorkflowRecipeSchema>;

/* --------------------------------------------------------- request schemas */

const Id = z.uuid();
const RequestId = z.string().min(8).max(80).regex(/^[A-Za-z0-9_-]+$/);
const TrimmedTitle = z.string().trim().min(1).max(120);

export const WorkflowRefChoiceSchema = z
  .object({
    assetId: Id.optional(),
    outputId: Id.optional(),
    role: z.enum(STUDIO_ASSET_ROLES).optional(),
  })
  .refine((r) => (r.assetId === undefined) !== (r.outputId === undefined), { error: 'assetId or outputId' });
export type WorkflowRefChoice = z.infer<typeof WorkflowRefChoiceSchema>;

export const WorkflowCreateSchema = z.object({
  organizationId: Id,
  requestId: RequestId,
  title: TrimmedTitle,
  summary: z.string().trim().max(400).default(''),
  category: z.enum(WORKFLOW_CATEGORIES).default('custom'),
  slug: z.string().trim().min(1).max(80).optional(),
  source: z.enum(['saved_run', 'ai_builder', 'mcp', 'web']).default('web'),
  recipe: WorkflowRecipeSchema,
});
export type WorkflowCreateInput = z.infer<typeof WorkflowCreateSchema>;

export const WorkflowUpdateSchema = z.object({
  organizationId: Id,
  workflowId: Id,
  title: TrimmedTitle.optional(),
  summary: z.string().trim().max(400).optional(),
  category: z.enum(WORKFLOW_CATEGORIES).optional(),
  recipe: WorkflowRecipeSchema.optional(),
});
export type WorkflowUpdateInput = z.infer<typeof WorkflowUpdateSchema>;

export const WorkflowDeleteSchema = z.object({
  organizationId: Id,
  workflowId: Id,
});

export const WorkflowRunInputsSchema = z.object({
  image1Ref: WorkflowRefChoiceSchema.nullable().optional(),
  video1Ref: WorkflowRefChoiceSchema.nullable().optional(),
  subject: z.string().trim().max(80).optional(),
  prompt: z.string().trim().max(2400).default(''),
  packs: z.array(z.string().trim().min(1).max(40)).max(8).optional(),
  folderName: z.string().trim().max(60).optional(),
});
export type WorkflowRunInputs = z.infer<typeof WorkflowRunInputsSchema>;

export const WorkflowRunSchema = z.object({
  organizationId: Id,
  requestId: RequestId,
  /** Accepts an org workflow UUID, `starter:<slug>`, or bare `<slug>`. */
  workflowId: z.string().trim().min(1).max(100),
  inputs: WorkflowRunInputsSchema.default({ prompt: '' }),
});
export type WorkflowRunInput = z.infer<typeof WorkflowRunSchema>;

export const WorkflowSaveFromJobSchema = z.object({
  organizationId: Id,
  requestId: RequestId,
  jobId: Id,
  title: TrimmedTitle,
  summary: z.string().trim().max(400).default(''),
  category: z.enum(WORKFLOW_CATEGORIES).optional(),
});
export type WorkflowSaveFromJobInput = z.infer<typeof WorkflowSaveFromJobSchema>;

export const WorkflowBuildWithAiSchema = z.object({
  organizationId: Id,
  requestId: RequestId,
  brief: z.string().trim().min(4).max(1600),
});
export type WorkflowBuildWithAiInput = z.infer<typeof WorkflowBuildWithAiSchema>;

export const PlaybookSaveSchema = z.object({
  organizationId: Id,
  requestId: RequestId,
  playbookId: Id.optional(),
  title: TrimmedTitle,
  bodyMd: z.string().trim().max(12_000).default(''),
  tags: z.array(z.string().trim().min(1).max(24)).max(10).default([]),
  injectDirector: z.boolean().default(false),
  status: z.enum(PLAYBOOK_STATUSES).default('published'),
});
export type PlaybookSaveInput = z.infer<typeof PlaybookSaveSchema>;

export const PlaybookDeleteSchema = z.object({
  organizationId: Id,
  playbookId: Id,
});

/* -------------------------------------------------------------- wire views */

export interface WorkflowWire {
  id: string;
  slug: string;
  title: string;
  titleEn?: string;
  summary: string;
  summaryEn?: string;
  category: WorkflowCategory;
  source: WorkflowSource;
  starter: boolean;
  revision: number;
  stepCount: number;
  estimatedCredits: number;
  recipe: WorkflowRecipe;
  updatedAt: string;
}

export interface PlaybookWire {
  id: string;
  title: string;
  bodyMd: string;
  tags: string[];
  injectDirector: boolean;
  status: PlaybookStatus;
  updatedAt: string;
}

export interface RecentRunSummaryWire {
  jobId: string;
  kind: StudioJobKind;
  model: string;
  aspect: string | null;
  resolution: string | null;
  seconds: number | null;
  audio: StudioAudioMode | null;
  prompt: string;
  referenceRoles: Array<StudioAssetRole | 'media'>;
  thumbUrl: string | null;
  createdAt: string;
}

export interface CharacterConsistencyReport {
  checked: boolean;
  passed: boolean;
  score: number;
  retried: boolean;
  retriedStepId: string | null;
  mode: 'gemini-vision' | 'deterministic-fallback';
  driftedLabels: string[];
  notes: string;
}

export interface WorkflowsHubState {
  ok: true;
  canCreate: boolean;
  allowance: StudioAllowanceView;
  starters: WorkflowWire[];
  workflows: WorkflowWire[];
  playbooks: PlaybookWire[];
  recentRuns: RecentRunSummaryWire[];
}

export interface WorkflowSavedResult {
  ok: true;
  workflow: WorkflowWire;
  builderMode?: 'gemini' | 'fallback';
}

export interface PlaybookSavedResult {
  ok: true;
  playbook: PlaybookWire;
}

export interface WorkflowDeletedResult {
  ok: true;
}

export interface WorkflowRunResult {
  ok: true;
  workflowId: string;
  workflowSlug: string;
  jobs: StudioJobView[];
  folder: { id: string; name: string } | null;
  consistency: CharacterConsistencyReport | null;
  allowance: StudioAllowanceView;
}

export type WorkflowOperationResult =
  | StudioFailure
  | WorkflowSavedResult
  | PlaybookSavedResult
  | WorkflowDeletedResult
  | WorkflowRunResult;
