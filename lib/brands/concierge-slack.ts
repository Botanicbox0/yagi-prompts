import { createHash, randomUUID } from 'node:crypto';
import type { SqlRunner } from '@/lib/db/sql-runner';

export const DEFAULT_CONCIERGE_SLACK_CHANNEL = 'C0C7V2PB079'; // #sales-inbox

export interface ConciergeOrganizationRef {
  id: string;
  name: string;
}

/**
 * Generates the canonical `@handle` tag shown in Slack for a brand organization.
 * Example: "Morphic" -> "@morphic", "YAGI WORKSHOP TEST" -> "@yagi-workshop-test"
 */
export function brandSlackHandle(name: string): string {
  const slug = name
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9가-힣]+/g, '-')
    .replace(/^-+|-+$/g, '');
  return `@${slug || 'brand'}`;
}

function candidateHandles(name: string): string[] {
  const trimmed = name.trim().toLowerCase();
  const slug = trimmed.replace(/[^a-z0-9가-힣]+/g, '-').replace(/^-+|-+$/g, '');
  const compact = trimmed.replace(/[^a-z0-9가-힣]+/g, '');
  const firstWord = trimmed.split(/[^a-z0-9가-힣]+/).filter(Boolean)[0] ?? '';
  return Array.from(new Set([slug, compact, firstWord].filter((s) => s.length >= 2)));
}

/**
 * Deterministic UUID v4-shaped identifier from a Slack message `(channelId, ts)` pair,
 * ensuring the exact same Slack message is never inserted twice into `brand_support_messages`.
 */
export function deterministicSlackMessageUuid(channelId: string, ts: string): string {
  const hex = createHash('sha256').update(`slack-concierge:${channelId}:${ts}`).digest('hex');
  return [
    hex.slice(0, 8),
    hex.slice(8, 12),
    `4${hex.slice(13, 16)}`,
    `a${hex.slice(17, 20)}`,
    hex.slice(20, 32),
  ].join('-');
}

/**
 * Parses a Slack message to determine if it is a reply targeted at a brand organization.
 * Supports:
 * 1. Direct mention prefix: `@morphic 안녕하세요 ...`, `[@morphic] ...`, `@morphic: ...`
 * 2. Thread reply under a parent message carrying `[org:<uuid>]`
 */
export function parseSlackConciergeReply(
  rawText: string,
  organizations: readonly ConciergeOrganizationRef[],
  parentText?: string | null,
): { organizationId: string; body: string } | null {
  const text = rawText.trim();
  if (!text) return null;
  // Ignore outbound notifications generated by the concierge bridge itself
  if (text.includes('[brand.twings.app 실시간 문의]') || text.includes('[org:')) {
    return null;
  }

  // 1. Check explicit @<brand> prefix at the start of the message
  const mentionMatch = /^\[?@([a-zA-Z0-9가-힣_-]+)\]?[\s,:;-]+([\s\S]+)$/.exec(text);
  if (mentionMatch) {
    const token = mentionMatch[1]!.toLowerCase();
    const replyBody = mentionMatch[2]!.trim();
    if (!replyBody) return null;

    // Exact slug/compact match first, then first-word match
    const matched =
      organizations.find((org) => {
        const [slug, compact] = candidateHandles(org.name);
        return token === slug || token === compact || token === org.id.toLowerCase();
      }) ??
      organizations.find((org) => candidateHandles(org.name).includes(token));

    if (matched) {
      return { organizationId: matched.id, body: replyBody };
    }
  }

  // 2. If this message is a thread reply to an inquiry message containing `[org:UUID]`
  if (parentText) {
    const orgMatch = /\[org:([0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12})\]/i.exec(
      parentText,
    );
    if (orgMatch) {
      const orgId = orgMatch[1]!.toLowerCase();
      const matched = organizations.find((o) => o.id.toLowerCase() === orgId);
      if (matched) {
        // Strip leading Slack user mention `<@U...>` if someone replied by mentioning the bot
        const cleaned = text.replace(/^(?:<@[A-Z0-9]+>\s*)+/, '').trim();
        if (cleaned) {
          return { organizationId: matched.id, body: cleaned };
        }
      }
    }
  }

  return null;
}

export interface ConciergeSlackConfig {
  enabled: boolean;
  token: string;
  channelId: string;
}

export function resolveConciergeSlackConfig(
  env: Record<string, string | undefined> = process.env,
): ConciergeSlackConfig | null {
  // Never run live Slack calls inside automated unit tests unless explicitly enabled for test harness
  if (env.VITEST && env.SLACK_BRAND_CONCIERGE_FORCE_TEST !== 'on') return null;
  if (env.SLACK_BRAND_CONCIERGE_ENABLED === 'off') return null;
  const token = (env.SLACK_BRAND_CONCIERGE_BOT_TOKEN ?? env.SLACK_BOT_TOKEN)?.trim();
  if (!token || !token.startsWith('xoxb-')) return null;
  const channelId = env.SLACK_BRAND_CONCIERGE_CHANNEL_ID?.trim() || DEFAULT_CONCIERGE_SLACK_CHANNEL;
  return { enabled: true, token, channelId };
}

export function formatOutboundSlackInquiry(input: {
  organizationId: string;
  organizationName: string;
  senderEmail: string;
  senderRole: string;
  body: string;
  messageId: string;
}): string {
  const handle = brandSlackHandle(input.organizationName);
  const quotedBody = input.body
    .split(/\r?\n/)
    .map((line) => `> ${line}`)
    .join('\n');
  return [
    `💬 *[brand.twings.app 실시간 문의]*`,
    `• *고객사:* *${input.organizationName}* (\`${handle}\`)`,
    `• *보낸 사람:* ${input.senderEmail} (${input.senderRole})`,
    `• *문의 내용:*`,
    quotedBody,
    `↩️ _답변 방법: 이 채널에 \`${handle} 답변내용\`을 입력하거나, 이 메시지의 *스레드(댓글)*로 답장하면 고객사 채팅창으로 즉시 전송됩니다._ \`[org:${input.organizationId}]\` \`[msg:${input.messageId}]\``,
  ].join('\n');
}

/**
 * Sends a brand inquiry notification to the configured Slack channel.
 * Best-effort with a strict timeout so the user's chat send never blocks or fails if Slack is slow.
 */
export async function notifySlackBrandConcierge(
  sql: SqlRunner,
  input: {
    organizationId: string;
    userId: string;
    body: string;
    messageId: string;
  },
  options?: {
    env?: Record<string, string | undefined>;
    fetcher?: typeof fetch;
    timeoutMs?: number;
  },
): Promise<{ sent: boolean; ts?: string }> {
  const config = resolveConciergeSlackConfig(options?.env);
  if (!config) return { sent: false };

  try {
    const orgRow = (
      await sql.query<{ name: string }>(
        'select name from brand_organizations where id=$1',
        [input.organizationId],
      )
    ).rows[0];
    const userRow = (
      await sql.query<{ email: string; is_admin: boolean }>(
        'select email, is_admin from profiles where id=$1',
        [input.userId],
      )
    ).rows[0];
    const memberRow = (
      await sql.query<{ role: string }>(
        "select role from brand_memberships where organization_id=$1 and user_id=$2 and status='active'",
        [input.organizationId, input.userId],
      )
    ).rows[0];

    const organizationName = orgRow?.name ? String(orgRow.name) : 'Brand Client';
    const senderEmail = userRow?.email ? String(userRow.email) : 'client@brand.twings.app';
    const senderRole = memberRow?.role
      ? String(memberRow.role)
      : userRow?.is_admin
        ? 'studio'
        : 'member';

    const text = formatOutboundSlackInquiry({
      organizationId: input.organizationId,
      organizationName,
      senderEmail,
      senderRole,
      body: input.body,
      messageId: input.messageId,
    });

    const fetcher = options?.fetcher ?? fetch;
    const controller = new AbortController();
    const timer = setTimeout(() => controller.abort(), options?.timeoutMs ?? 4500);
    try {
      const response = await fetcher('https://slack.com/api/chat.postMessage', {
        method: 'POST',
        signal: controller.signal,
        headers: {
          Authorization: `Bearer ${config.token}`,
          'Content-Type': 'application/json; charset=utf-8',
        },
        body: JSON.stringify({
          channel: config.channelId,
          text,
          unfurl_links: false,
          unfurl_media: false,
        }),
      });
      if (!response.ok) return { sent: false };
      const data = (await response.json()) as { ok?: boolean; ts?: string };
      return { sent: data.ok === true, ts: data.ts };
    } finally {
      clearTimeout(timer);
    }
  } catch {
    return { sent: false };
  }
}

const lastSyncByChannel = new Map<string, number>();

/**
 * Pulls recent Slack messages and thread replies from the concierge channel and inserts
 * any `@<brand>` mentions or thread replies into `brand_support_messages` (`author_role = 'studio'`).
 */
export async function syncSlackConciergeReplies(
  sql: SqlRunner,
  organizationId?: string,
  options?: {
    env?: Record<string, string | undefined>;
    fetcher?: typeof fetch;
    force?: boolean;
  },
): Promise<number> {
  const config = resolveConciergeSlackConfig(options?.env);
  if (!config) return 0;

  const now = Date.now();
  const last = lastSyncByChannel.get(config.channelId) ?? 0;
  if (!options?.force && now - last < 2500) {
    return 0;
  }
  lastSyncByChannel.set(config.channelId, now);

  try {
    const fetcher = options?.fetcher ?? fetch;
    const headers = { Authorization: `Bearer ${config.token}` };

    const histResp = await fetcher(
      `https://slack.com/api/conversations.history?channel=${encodeURIComponent(config.channelId)}&limit=35`,
      { method: 'GET', headers },
    );
    if (!histResp.ok) return 0;
    const histData = (await histResp.json()) as {
      ok?: boolean;
      messages?: Array<{
        ts?: string;
        text?: string;
        bot_id?: string;
        subtype?: string;
        thread_ts?: string;
        reply_count?: number;
      }>;
    };
    if (!histData.ok || !Array.isArray(histData.messages)) return 0;

    const orgRows = (
      await sql.query<{ id: string; name: string }>(
        'select id, name from brand_organizations order by created_at desc',
      )
    ).rows.map((r) => ({ id: String(r.id), name: String(r.name) }));
    if (!orgRows.length) return 0;

    const candidates: Array<{ ts: string; organizationId: string; body: string }> = [];

    // 1. Check top-level channel messages for `@<brand> ...` replies (chronological order: oldest first)
    const ordered = [...histData.messages].reverse();
    for (const msg of ordered) {
      if (!msg.ts || !msg.text || msg.subtype) continue;
      const parsed = parseSlackConciergeReply(msg.text, orgRows);
      if (parsed && (!organizationId || parsed.organizationId === organizationId)) {
        candidates.push({ ts: msg.ts, ...parsed });
      }
    }

    // 2. Check thread replies on recent inquiry messages that have `reply_count > 0`
    const threadedParents = histData.messages.filter(
      (m) =>
        m.ts &&
        m.text &&
        (m.reply_count ?? 0) > 0 &&
        m.text.includes('[org:') &&
        (!organizationId || m.text.includes(`[org:${organizationId}]`)),
    );

    for (const parent of threadedParents.slice(0, 5)) {
      const repResp = await fetcher(
        `https://slack.com/api/conversations.replies?channel=${encodeURIComponent(config.channelId)}&ts=${encodeURIComponent(parent.ts!)}&limit=20`,
        { method: 'GET', headers },
      );
      if (!repResp.ok) continue;
      const repData = (await repResp.json()) as {
        ok?: boolean;
        messages?: Array<{ ts?: string; text?: string; subtype?: string }>;
      };
      if (!repData.ok || !Array.isArray(repData.messages)) continue;
      for (const reply of repData.messages) {
        if (!reply.ts || reply.ts === parent.ts || !reply.text || reply.subtype) continue;
        const parsed = parseSlackConciergeReply(reply.text, orgRows, parent.text);
        if (parsed && (!organizationId || parsed.organizationId === organizationId)) {
          candidates.push({ ts: reply.ts, ...parsed });
        }
      }
    }

    if (!candidates.length) return 0;

    // Resolve a studio author user_id (first admin profile, or fallback to any member of the target org)
    const adminRow = (
      await sql.query<{ id: string }>(
        'select id from profiles where is_admin = true order by created_at asc limit 1',
      )
    ).rows[0];

    let inserted = 0;
    for (const item of candidates) {
      const requestId = deterministicSlackMessageUuid(config.channelId, item.ts);
      const exists = (
        await sql.query<{ id: string }>(
          'select id from brand_support_messages where organization_id=$1 and request_id=$2 limit 1',
          [item.organizationId, requestId],
        )
      ).rows[0];
      if (exists) continue;

      let authorUserId = adminRow?.id ? String(adminRow.id) : null;
      if (!authorUserId) {
        const fallbackMember = (
          await sql.query<{ user_id: string }>(
            'select user_id from brand_memberships where organization_id=$1 limit 1',
            [item.organizationId],
          )
        ).rows[0];
        authorUserId = fallbackMember?.user_id ? String(fallbackMember.user_id) : null;
      }
      if (!authorUserId) continue;

      await sql.query(
        `insert into brand_support_messages(id, organization_id, body, author_role, created_by, request_id)
         values ($1, $2, $3, 'studio', $4, $5)
         on conflict (organization_id, created_by, request_id) do nothing`,
        [randomUUID(), item.organizationId, item.body.slice(0, 4000), authorUserId, requestId],
      );
      inserted += 1;
    }

    return inserted;
  } catch {
    return 0;
  }
}
